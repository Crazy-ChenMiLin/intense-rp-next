def zh(value: Any) -> str:
    text = str(value or "")
    if not text:
        return text

    direct = _TEXT.get(text)
    if direct is not None:
        return direct

    translated = text
    for source, target in _PHRASES:
        translated = translated.replace(source, target)
    return translated
